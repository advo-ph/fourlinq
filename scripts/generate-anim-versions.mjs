/**
 * generate-anim-versions.mjs
 *
 * Emits src/generated/anim-versions.json — one short content hash per system
 * hover-animation set under public/systems/anim/<id>/.
 *
 * WHY THIS EXISTS
 *
 * The frame filenames are fixed (01.webp … 28.webp) and are replaced in place
 * whenever a set is re-baked or re-imported. server/index.ts serves everything
 * under dist/ that is not HTML and not /images/ with `max-age=365d, immutable`,
 * which is correct for Vite's content-addressed JS/CSS but wrong for these:
 * a browser that ever loaded a frame keeps it for a year and, because of
 * `immutable`, does not even revalidate. Replacing a set was therefore
 * invisible to every returning visitor.
 *
 * Relaxing the header alone cannot fix that — the already-cached response
 * carries `immutable`, so the browser will not re-ask regardless of what the
 * server says next. Only a changed URL forces a miss, which is what the ?v=
 * token appended in src/data/systemAnimations.ts does.
 *
 * This mirrors the /images/ fix already in the repo (see
 * scripts/generate-project-thumbs.mjs and src/lib/image-version.ts); the only
 * difference is granularity. Versioning is per SET, not per frame: the bake and
 * import scripts always rewrite all 28 frames together, so a set is the real
 * unit of change, and one token for 14 systems beats 392 near-identical ones.
 *
 * The manifest is committed so the dev server is accurate without an extra
 * step, and regenerated by `prebuild` so a forgotten run cannot ship a stale
 * token.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ANIM_DIR = path.join(ROOT, "public", "systems", "anim");
const MANIFEST_DIR = path.join(ROOT, "src", "generated");
const MANIFEST_PATH = path.join(MANIFEST_DIR, "anim-versions.json");

const dirs = (await readdir(ANIM_DIR, { withFileTypes: true }))
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const versions = {};
for (const id of dirs) {
  const frames = (await readdir(path.join(ANIM_DIR, id)))
    .filter((f) => /^\d+\.webp$/.test(f))
    .sort();
  if (frames.length === 0) continue;

  // Hash the frames in order, and the filenames with them, so that adding or
  // removing a trailing frame changes the token even if the surviving bytes
  // are untouched.
  const h = createHash("md5");
  for (const f of frames) {
    h.update(f);
    h.update(await readFile(path.join(ANIM_DIR, id, f)));
  }
  versions[id] = h.digest("hex").slice(0, 8);
}

await mkdir(MANIFEST_DIR, { recursive: true });
await writeFile(
  MANIFEST_PATH,
  `${JSON.stringify(
    {
      _note:
        "Auto-generated by scripts/generate-anim-versions.mjs (prebuild). Do not edit manually.",
      ...versions,
    },
    null,
    2,
  )}\n`,
);

console.log(
  `[anim-versions] Manifest written → src/generated/anim-versions.json (${Object.keys(versions).length} sets)`,
);
